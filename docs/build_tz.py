def _set_font(run, bold=False, italic=False, size=SIZE):
    run.font.name = FONT
    run.font.size = size
    run.font.bold = bold
    run.font.italic = italic
    r = run._element.rPr
    rf = r.find(qn("w:rFonts"))
    if rf is None:
        rf = OxmlElement("w:rFonts")
        r.insert(0, rf)
    rf.set(qn("w:eastAsia"), FONT)


def body(text, indent=True, align="justify", bold=False, italic=False, after=0):
    p = doc.add_paragraph()
    p.paragraph_format.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
    if indent:
        p.paragraph_format.first_line_indent = Mm(12.5)
    p.paragraph_format.space_after = Pt(after)
    p.alignment = {"justify": WD_ALIGN_PARAGRAPH.JUSTIFY,
                   "center": WD_ALIGN_PARAGRAPH.CENTER,
                   "left": WD_ALIGN_PARAGRAPH.LEFT,
                   "right": WD_ALIGN_PARAGRAPH.RIGHT}[align]
    r = p.add_run(text)
    _set_font(r, bold=bold, italic=italic)
    return p


def bullet(text, dash="–"):
    p = doc.add_paragraph()
    p.paragraph_format.line_spacing_rule = WD_LINE_SPACING.ONE_POINT_FIVE
    p.paragraph_format.first_line_indent = Mm(12.5)
    p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    r = p.add_run(f"{dash} {text}")
    _set_font(r)
    return p


